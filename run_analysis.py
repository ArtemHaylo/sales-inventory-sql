"""
Run every query in sql/03_analytics.sql with psql, save each result to
results/qNN.csv and build results/RESULTS.md (one markdown table per query).

Usage:  python run_analysis.py "psql -d abc_corp"
"""
import csv
import io
import os
import re
import shlex
import subprocess
import sys

PSQL = shlex.split(sys.argv[1] if len(sys.argv) > 1 else "psql -d abc_corp")
ROOT = os.path.dirname(os.path.abspath(__file__))
os.makedirs(os.path.join(ROOT, "results"), exist_ok=True)

sql = open(os.path.join(ROOT, "sql", "03_analytics.sql"), encoding="utf-8").read()
blocks = re.split(r"\n(?=-- Q\d+\. )", sql)[1:]

md = ["# Query results\n", "Generated by `run_analysis.py` from `sql/03_analytics.sql`.\n"]
for block in blocks:
    title = block.splitlines()[0].lstrip("- ").rstrip("- ").strip()
    num = int(re.match(r"Q(\d+)", title).group(1))
    out = subprocess.run(PSQL + ["--csv", "-v", "ON_ERROR_STOP=1", "-c", block],
                         capture_output=True, text=True, check=True).stdout
    with open(os.path.join(ROOT, "results", f"q{num:02d}.csv"), "w", encoding="utf-8") as fh:
        fh.write(out)
    rows = list(csv.reader(io.StringIO(out)))
    md.append(f"\n## {title}\n")
    md.append("| " + " | ".join(rows[0]) + " |")
    md.append("|" + "---|" * len(rows[0]))
    for r in rows[1:]:
        md.append("| " + " | ".join(r) + " |")
open(os.path.join(ROOT, "results", "RESULTS.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
print(f"{len(blocks)} queries executed")
